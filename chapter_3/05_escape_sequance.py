
# \n - for next line

a = "hello i am yash \n i am a cse student"

print(a)

# \t - for tab size space

a = "hello i am yash \t i am a cse student"

print(a)

# \"" - for double quates in string

b = "hello i am yash \" i am a cse student\""

print(b)

# \\ - for baclslash

a = "hello i am yash \\ i am a cse student"
print(a)
